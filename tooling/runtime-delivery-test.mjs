#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { readFile, writeFile, mkdir, readdir, copyFile, chmod } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import JSZip from 'jszip';
import { runtimeWalkthroughProject } from './runtime-walkthrough-fixture.mjs';
import { runtimeProductProject } from './runtime-product-fixture.mjs';
import { runtimeDoorAuditProject } from './runtime-door-audit-fixture.mjs';
import { runtimeMultileafProject } from './runtime-multileaf-fixture.mjs';
import { runtimeSupportProject } from './runtime-support-fixture.mjs';
import {runtimeLightingReferenceProject} from './runtime-lighting-reference-fixture.mjs';
import {architectureCorrectionProject,architectureEntranceProject} from './runtime-architecture-correction-fixture.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const [playerZip, output] = process.argv.slice(2);
if (!playerZip || !output || process.argv.length !== 4) {
  console.error('Usage: node tooling/runtime-delivery-test.mjs <player.zip> <new-output-directory>');
  process.exit(2);
}
const directory = path.resolve(output);
if ((await readdir(directory).catch(error => { if (error.code === 'ENOENT') return []; throw error; })).length) {
  throw new Error('Delivery test output must be empty or new.');
}
await mkdir(directory, { recursive: true });
const input = path.join(directory, 'native.project.json');
const source = JSON.stringify(await runtimeWalkthroughProject());
await writeFile(input, source);
const sceneZip = path.join(directory, 'scene.zip');
execFileSync(process.execPath, [path.join(root, 'tooling/runtime-export.mjs'), input, '--package', sceneZip], { cwd: root, stdio: 'inherit' });

// The ZIPs are generated by this repository. Extract exactly what a user gets;
// neither the executable nor its scene may rely on the checkout working dir.
async function extract(zipPath, destination) {
  const zip = await JSZip.loadAsync(await readFile(zipPath), { checkCRC32: true });
  for (const entry of Object.values(zip.files)) {
    const file = path.join(destination, entry.name);
    if (entry.dir) { await mkdir(file, { recursive: true }); continue; }
    await mkdir(path.dirname(file), { recursive: true });
    await writeFile(file, await entry.async('uint8array'));
    if (typeof entry.unixPermissions === 'number') await chmod(file, entry.unixPermissions & 0o777);
  }
}
const playerDirectory = path.join(directory, '搬移后的播放器 with spaces');
const sceneDirectory = path.join(directory, '离线场景 with spaces');
await extract(path.resolve(playerZip), playerDirectory);
await extract(sceneZip, sceneDirectory);
const executable = path.join(playerDirectory, process.platform === 'win32' ? 'Plan2World.exe' : 'Plan2World.x86_64');
const scene = path.join(sceneDirectory, 'scene.runtime.json');
const productInput = path.join(directory, 'product.project.json');
const productSource = JSON.stringify(await runtimeProductProject());
await writeFile(productInput, productSource);
const multileafInput=path.join(directory,'multileaf.project.json'),multileafScene=path.join(directory,'multileaf.runtime.json');
await writeFile(multileafInput,JSON.stringify(await runtimeMultileafProject()));
execFileSync(process.execPath,[path.join(root,'tooling/runtime-export.mjs'),multileafInput,multileafScene],{cwd:root,stdio:'inherit'});
const supportInput=path.join(directory,'support.project.json');await writeFile(supportInput,JSON.stringify(await runtimeSupportProject()));
const lightingInput=path.join(directory,'lighting-reference.project.json');await writeFile(lightingInput,JSON.stringify(await runtimeLightingReferenceProject()));
const correctionDirectory=path.join(directory,'architecture-correction');await mkdir(correctionDirectory);
for (const [name,broken,offset] of [['valid',false,0],['broken',true,0],['fractional',false,.125]]) await writeFile(path.join(correctionDirectory,name+'.project.json'),JSON.stringify(architectureCorrectionProject(broken,offset)));
await writeFile(path.join(correctionDirectory,'entrance.project.json'),JSON.stringify(architectureEntranceProject()));
const godot = process.env.GODOT_BIN || 'godot';
if (!(await readFile(path.join(playerDirectory, 'README.zh-CN.md'), 'utf8')).includes('用法一：插件 / Skill')) throw new Error('Player is missing its two-entry user guide.');
for (const filename of ['runtime_launcher_test.gd', 'runtime_walkthrough_test.gd', 'runtime_layout_test.gd', 'runtime_product_controls_test.gd', 'runtime_snapping_test.gd', 'runtime_snapping_controls_test.gd', 'runtime_layout_ui_test.gd', 'runtime_desktop_authoring_test.gd', 'runtime_plan_lighting_test.gd', 'runtime_interaction_test.gd', 'runtime_multileaf_test.gd', 'runtime_support_test.gd', 'runtime_placement_preview_test.gd', 'runtime_lighting_reference_test.gd', 'runtime_architecture_correction_test.gd', 'runtime_object_editing_test.gd', 'runtime_spatial_authoring_test.gd']) {
  const script = path.join(directory, filename);
  await copyFile(path.join(root, 'runtime/godot/tests', filename), script);
  const args = filename === 'runtime_launcher_test.gd' ? [scene, '--require-packed']
    : filename === 'runtime_layout_test.gd' ? [input, path.join(directory, 'layout')]
    : filename === 'runtime_product_controls_test.gd' ? [productInput, path.join(directory, 'controls'), path.join(sceneDirectory, 'scene.architecture.glb')]
    : filename === 'runtime_snapping_controls_test.gd' ? [productInput, path.join(directory, 'snapping')]
    : filename === 'runtime_layout_ui_test.gd' ? [productInput, path.join(directory, 'furnishing-ui')]
    : filename === 'runtime_desktop_authoring_test.gd' ? [productInput, path.join(directory, 'desktop-authoring')]
    : filename === 'runtime_plan_lighting_test.gd' ? [productInput, path.join(directory, 'plan-lighting')]
    : filename === 'runtime_multileaf_test.gd' ? [multileafScene,multileafInput]
    : filename === 'runtime_support_test.gd' ? [supportInput]
    : filename === 'runtime_placement_preview_test.gd' ? [productInput,path.join(directory,'placement-preview')]
    : filename === 'runtime_lighting_reference_test.gd' ? [lightingInput,path.join(directory,'lighting-reference')]
    : filename === 'runtime_architecture_correction_test.gd' ? [correctionDirectory]
    : filename === 'runtime_object_editing_test.gd' ? [productInput,path.join(directory,'object-editing')]
    : filename === 'runtime_spatial_authoring_test.gd' ? [path.join(correctionDirectory,'valid.project.json'),path.join(directory,'spatial-authoring')]
    : ['runtime_snapping_test.gd', 'runtime_interaction_test.gd'].includes(filename) ? []
    : ['--scene', scene];
  // Official release templates disable --script/path overrides. Use the pinned
  // editor to exercise the exact shipped PCK; do not add test hooks to the game.
  execFileSync(godot, ['--headless', '--main-pack', path.join(playerDirectory, 'Plan2World.pck'), '--fixed-fps', '60', '--script', script, '--', ...args], { cwd: directory, stdio: 'inherit', timeout: 180_000, env: { ...process.env, P2W_AUTHORING_CORE: path.join(playerDirectory, 'core') } });
}
// A real per-door audit must distinguish healthy motion, physical obstruction,
// explicit unsupported motion and a leafless passage. Use the shipped loader
// and physics from the exact PCK, with no actor or presentation-derived shapes.
const doorAuditScript=path.join(directory,'runtime-door-audit.gd');
await copyFile(path.join(root,'tooling/runtime-door-audit.gd'),doorAuditScript);
async function auditDoors(runtimePath,reportPath) {
  execFileSync(godot,['--headless','--main-pack',path.join(playerDirectory,'Plan2World.pck'),'--fixed-fps','60','--script',doorAuditScript,'--',runtimePath,reportPath],{cwd:directory,stdio:'inherit',timeout:180_000});
  return JSON.parse(await readFile(reportPath,'utf8'));
}
const healthy=await auditDoors(scene,path.join(directory,'healthy-door-motion.json'));
if(healthy.status!=='pass'||healthy.doors.length!==4||healthy.doors.some(door=>door.status!=='pass'||!door.fullyOpen||!door.fullyClosed))throw new Error('Every supported fixture door must fully open and close in isolation.');
const blockedInput=path.join(directory,'blocked-doors.project.json'),blockedScene=path.join(directory,'blocked-doors.runtime.json');
await writeFile(blockedInput,JSON.stringify(await runtimeDoorAuditProject()));
execFileSync(process.execPath,[path.join(root,'tooling/runtime-export.mjs'),blockedInput,blockedScene],{cwd:root,stdio:'inherit'});
const blocked=await auditDoors(blockedScene,path.join(directory,'blocked-door-motion.json'));
const byId=new Map(blocked.doors.map(door=>[door.id,door])),slide=byId.get('slide-door');
if(blocked.status!=='fail'||slide?.status!=='fail'||slide.fullyOpen||!slide.fullyClosed||!slide.leaves.some(leaf=>leaf.openPoseBlockers.includes('slide-travel-blocker')))throw new Error('Door audit must report an authored travel blocker without bypassing or repairing it.');
if(byId.get('unsupported-fold')?.status!=='review_required'||byId.get('unsupported-overhead')?.status!=='review_required'||byId.get('leafless')?.status!=='pass')throw new Error('Unsupported motion and leafless passages must retain their explicit semantics in acceptance.');
// Also boot the shipped application normally, without the external test script.
// Windows GUI executables may have no console stdout. The engine's own log-file
// option gives both platforms the same observable production load diagnostics.
const bootLog = path.join(directory, 'release-boot.log');
execFileSync(executable, ['--headless', '--log-file', bootLog, '--quit-after', '30', '--', '--scene', scene], { cwd: directory, stdio: ['ignore', 'ignore', 'inherit'], timeout: 30_000 });
const boot = await readFile(bootLog, 'utf8');
console.log(boot);
if (!boot.includes('Plan2World runtime loaded:') || !boot.includes('assets=8') || !boot.includes('"collider_proxy_count": 0')) {
  throw new Error('Release executable failed to load the complete fixture presentation');
}
if (await readFile(input, 'utf8') !== source) throw new Error('Native source changed during export');
if (await readFile(productInput, 'utf8') !== productSource) throw new Error('Native product source changed during editing');
console.log('Relocated player/scene ZIPs: eighteen gate groups including spatial paving/opening preview and protected wall marks, contextual object editing, native architecture correction, lighting/decor reference, spatial preview, footprint support, multi-leaf routes, local photo preparation, mocked recognition and every-door motion + offline shared core + release executable boot: PASS');
